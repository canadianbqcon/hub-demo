# ── Path helpers ──────────────────────────────────────────────────────────────


def _segments(rel_path: str) -> list[str]:
    """All path segments. '.' (vault root) -> []."""
    if rel_path in (".", _ROOT):
        return []
    return rel_path.split("/")


def _eff_segments(rel_path: str) -> list[str]:
    """Segments with the leading 'vault-code' stripped, so location-role rules
    (which key on the effective top folders) fire identically for both roots."""
    segs = _segments(rel_path)
    if segs and segs[0] == _CODE_PREFIX:
        segs = segs[1:]
    return segs


# ── Provenance + classification ───────────────────────────────────────────────


def _is_generated(segments: list[str], name: str, ext: str | None) -> bool:
    if any(s in _GEN_DIRS for s in segments):
        return True
    if ext in _GEN_EXT:
        return True
    if name == ".DS_Store":
        return True
    if ".min." in name:
        return True
    return False


@dataclass(frozen=True)
class _ClassifyCtx:
    """Intrinsic tells for one node, precomputed once so each classify rule below
    stays a plain one-line predicate instead of repeating segs/top2 lookups."""

    segs: list[str]
    top2: list[str]
    name: str
    ext: str | None
    generated: bool


# 10-bucket rules, first match wins. Each predicate is isolated to its own tiny
# function so `_classify` itself is just a loop — see the module docstring for
# why there is no silent default bucket.
def _rule_generated(c: _ClassifyCtx) -> bool:
    return c.generated  # 1. tool-generated / derived


def _rule_governance_file(c: _ClassifyCtx) -> bool:
    # 2. the rule files themselves
    return c.name == "CLAUDE.md" or (c.name.startswith("CLAUDE-") and c.name.endswith(".md"))


def _rule_claude_dir(c: _ClassifyCtx) -> bool:
    return ".claude" in c.segs  # 3. anything under .claude (skills, hooks, settings, plugins)


def _rule_ingest(c: _ClassifyCtx) -> bool:
    return "raw" in c.top2 or "Clippings" in c.top2  # 4. raw captures awaiting processing


def _rule_records(c: _ClassifyCtx) -> bool:
    # 5. operational history / working state
    return any(s in _RECORDS_PATH_DIRS for s in c.segs) or c.ext == ".log"


def _rule_data(c: _ClassifyCtx) -> bool:
    return c.ext in _DATA_EXT or "data" in c.top2  # 6. structured stores


def _rule_code(c: _ClassifyCtx) -> bool:
    return c.ext in _CODE_EXT  # 7. executable source


def _rule_config(c: _ClassifyCtx) -> bool:
    # 8. tool & system settings
    return c.ext in _CONFIG_EXT or c.name in _CONFIG_NAMES or ".obsidian" in c.segs


def _rule_asset(c: _ClassifyCtx) -> bool:
    return c.ext in _ASSET_EXT  # 9. media


def _rule_knowledge(c: _ClassifyCtx) -> bool:
    # 10. authored prose
    return c.ext == ".md" or any(s in _KNOWLEDGE_PATH_DIRS for s in c.segs)


_CLASSIFY_RULES: list[tuple[Callable[[_ClassifyCtx], bool], str]] = [
    (_rule_generated, "misc"),
    (_rule_governance_file, "governance"),
    (_rule_claude_dir, "governance"),
    (_rule_ingest, "ingest"),
    (_rule_records, "records"),
    (_rule_data, "data"),
    (_rule_code, "code"),
    (_rule_config, "config"),
    (_rule_asset, "asset"),
    (_rule_knowledge, "knowledge"),
]


def _classify(rel_path: str, name: str, ext: str | None, generated: bool) -> str:
    """The 10-bucket function for a node, by intrinsic tells, first match wins.
    `ext` is None for folders, so the extension rules are inert for them and only
    the location/name rules fire — which is why a code folder with no telling
    name (e.g. vault-code/dashboard) lands in `unclassified`, by design."""
    segs = _eff_segments(rel_path)
    ctx = _ClassifyCtx(segs=segs, top2=segs[:2], name=name, ext=ext, generated=generated)
    for rule, bucket in _CLASSIFY_RULES:
        if rule(ctx):
            return bucket
    # 11. no tell matched — surface it, don't bury it
    return "unclassified"


# ── Purpose extraction ────────────────────────────────────────────────────────


def _truncate(text: str, limit: int = 200) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _summary_from_markdown(text: str) -> str:
    """First prose paragraph of a markdown body, else the cleaned first H1."""
    h1 = ""
    in_fence = False
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        if line.startswith("#"):
            if not h1 and line.startswith("# "):
                h1 = line.lstrip("#").strip()
            continue
        if line.startswith(("---", "|", ">", "<!--")):
            continue
        return _truncate(line)
    if h1:
        h1 = re.sub(r"^CLAUDE\.md\s*[—\-–]\s*", "", h1)
        return _truncate(h1)
    return ""


# Durable AI-written descriptions (node_description table), loaded once per
# refresh. Preferred over canned by-type labels, never over authored content.
_DESCRIPTIONS: dict[str, str] = {}


def _load_descriptions() -> None:
    global _DESCRIPTIONS
    try:
        with _conn() as conn:
            _DESCRIPTIONS = {
                r["path"]: r["description"]
                for r in conn.execute("SELECT path, description FROM node_description")
            }
    except sqlite3.OperationalError:
        _DESCRIPTIONS = {}  # table not migrated yet


def _folder_purpose(
    abs_dir: Path, name: str, segments: list[str], rel_path: str
) -> str | None:
    """CLAUDE.md summary (authoritative) > AI description > git-internal canned
    desc (under .git) > system-dir canned desc > None."""
    claude = abs_dir / "CLAUDE.md"
    if claude.exists():
        summary = _summary_from_markdown(
            claude.read_text(encoding="utf-8", errors="replace")
        )
        if summary:
            return summary
    ai = _DESCRIPTIONS.get(rel_path)
    if ai:
        return ai
    if ".git" in segments:
        return _GIT_DIR_DESC.get(name)
    return _SYS_DIR_DESC.get(name)


def _file_purpose_and_type(
    abs_file: Path, rel_path: str, ext: str | None
) -> tuple[str | None, str | None, str | None]:
    """(purpose, wiki_type, wiki_slug) for a file node. Authored frontmatter
    summary wins; otherwise an AI description; otherwise a canned by-type label."""
    under_wiki = rel_path.startswith("wiki/")
    ai = _DESCRIPTIONS.get(rel_path)
    if ext == ".md":
        purpose, wiki_type = None, None
        try:
            post = frontmatter.load(str(abs_file))
            summary = str(post.metadata.get("summary", "")).strip()
            purpose = summary or _summary_from_markdown(post.content)
            if under_wiki:
                wiki_type = str(post.metadata.get("type", "")).strip() or None
        except Exception:
            purpose = _summary_from_markdown(
                abs_file.read_text(encoding="utf-8", errors="replace")
            )
        wiki_slug = rel_path[:-3] if under_wiki else None
        return (purpose or ai or None, wiki_type, wiki_slug)
    return (ai or _EXT_LABELS.get(ext or ""), None, None)


# ── Metadata ──────────────────────────────────────────────────────────────────

_LINE_LIMIT_BYTES = 2 * 1024 * 1024
# Extensions that get a line count — a fixed text allowlist (matches the design
# mockup). Deliberately excludes data (.csv), assets, and quirk-omitted siblings
# like .jsx/.jsonl; broaden here if real per-file line counts are wanted later.
_LINE_EXT = {
    ".py", ".md", ".json", ".html", ".txt", ".css", ".sh", ".js", ".yml", ".cfg",
    ".sql", ".toml",
}


def _mtime_date(abs_path: Path) -> str | None:
    try:
        return datetime.fromtimestamp(abs_path.stat().st_mtime).strftime("%Y-%m-%d")
    except OSError:
        return None


def _count_lines(abs_file: Path, size: int, generated: bool, ext: str | None) -> int | None:
    """Line count for authored text files in the allowlist under the size limit;
    None otherwise (generated, non-text ext, oversized, or undecodable)."""
    if generated or ext not in _LINE_EXT or size is None or size > _LINE_LIMIT_BYTES:
        return None
    try:
        text = abs_file.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError, ValueError):
        return None
    # newline count plus a trailing unterminated line, if any (matches the design
    # mockup). Not splitlines(), which also breaks on \r / unicode separators.
    return text.count("\n") + (1 if text and not text.endswith("\n") else 0)


def _ext_of(name: str) -> str | None:
    suffix = Path(name).suffix.lower()
    return suffix or None


# ── Walk + refresh ────────────────────────────────────────────────────────────


def _walk(abs_dir: Path, rel_dir: str, depth: int, rows: list) -> tuple[int, int]:
    """Recurse abs_dir, append node rows, return (file_count, subtree_bytes)."""
    try:
        entries = sorted(abs_dir.iterdir(), key=lambda p: p.name.lower())
    except OSError:
        return (0, 0)

    file_count = 0
    total_bytes = 0
    for entry in entries:
        child_rel = entry.name if rel_dir == "." else f"{rel_dir}/{entry.name}"
        segs = _segments(child_rel)
        if entry.is_dir():
            generated = _is_generated(segs, entry.name, None)
            sub_count, sub_bytes = _walk(entry, child_rel, depth + 1, rows)
            rows.append(
                {
                    "path": child_rel,
                    "parent_path": rel_dir,
                    "name": entry.name,
                    "node_kind": "folder",
                    "wiki_type": None,
                    "node_function": _classify(child_rel, entry.name, None, generated),
                    "purpose": _folder_purpose(entry, entry.name, segs, child_rel),
                    "file_count": sub_count,
                    "depth": depth + 1,
                    "wiki_slug": None,
                    "size": sub_bytes,
                    "mtime": _mtime_date(entry),
                    "lines": None,
                    "ext": None,
                    "generated": 1 if generated else 0,
                }
            )
            file_count += sub_count
            total_bytes += sub_bytes
        else:
            ext = _ext_of(entry.name)
            generated = _is_generated(segs, entry.name, ext)
            try:
                size = entry.stat().st_size
            except OSError:
                size = None
            purpose, wiki_type, wiki_slug = _file_purpose_and_type(entry, child_rel, ext)
            rows.append(
                {
                    "path": child_rel,
                    "parent_path": rel_dir,
                    "name": entry.name,
                    "node_kind": "file",
                    "wiki_type": wiki_type,
                    "node_function": _classify(child_rel, entry.name, ext, generated),
                    "purpose": purpose,
                    "file_count": 0,
                    "depth": depth + 1,
                    "wiki_slug": wiki_slug,
                    "size": size,
                    "mtime": _mtime_date(entry),
                    "lines": _count_lines(entry, size or 0, generated, ext),
                    "ext": ext,
                    "generated": 1 if generated else 0,
                }
            )
            file_count += 1
            total_bytes += size or 0
    return (file_count, total_bytes)


def _to_tuple(r: dict) -> tuple:
    return (
        r["path"], r["parent_path"], r["name"], r["node_kind"], r["wiki_type"],
        r["node_function"], r["purpose"], r["file_count"], r["depth"], r["wiki_slug"],
        r["size"], r["mtime"], r["lines"], r["ext"], r["generated"],
    )


def refresh() -> int:
    """Wipe map_node and repopulate from live walks of both roots under the
    synthetic '@' super-root. Returns the total node count written."""
    _load_descriptions()
    rows: list[dict] = []

    # Obsidian vault — children of '.', which sits under '@'.
    v_count, v_bytes = _walk(_VAULT_ROOT, ".", 1, rows)
    rows.append(
        {
            "path": ".", "parent_path": _ROOT, "name": "Obsidian Vault",
            "node_kind": "folder", "wiki_type": None, "node_function": "knowledge",
            "purpose": _VAULT_DESC, "file_count": v_count, "depth": 1, "wiki_slug": None,
            "size": v_bytes, "mtime": _mtime_date(_VAULT_ROOT), "lines": None,
            "ext": None, "generated": 0,
        }
    )

    # vault-code sibling — children prefixed 'vault-code/', root under '@'.
    c_count, c_bytes = _walk(_CODE_ROOT, _CODE_PREFIX, 1, rows)
    rows.append(
        {
            "path": _CODE_PREFIX, "parent_path": _ROOT, "name": "vault-code",
            "node_kind": "folder", "wiki_type": None, "node_function": "code",
            "purpose": _CODE_DESC, "file_count": c_count, "depth": 1, "wiki_slug": None,
            "size": c_bytes, "mtime": _mtime_date(_CODE_ROOT), "lines": None,
            "ext": None, "generated": 0,
        }
    )

    # Synthetic super-root.
    rows.append(
        {
            "path": _ROOT, "parent_path": None, "name": "second brain",
            "node_kind": "folder", "wiki_type": None, "node_function": "knowledge",
            "purpose": _SUPERROOT_DESC, "file_count": v_count + c_count, "depth": 0,
            "wiki_slug": None, "size": v_bytes + c_bytes, "mtime": None, "lines": None,
            "ext": None, "generated": 0,
        }
    )

    with _conn() as conn:
        conn.execute("DELETE FROM map_node")
        conn.executemany(_INSERT_SQL, [_to_tuple(r) for r in rows])
    return len(rows)


# ── Read queries ──────────────────────────────────────────────────────────────


def get_tree() -> list[dict]:
    with _conn() as conn:
        rows = conn.execute("SELECT * FROM map_node ORDER BY depth, path").fetchall()
    return [dict(r) for r in rows]


def get_children(parent_path: str) -> list[dict]:
    with _conn() as conn:
        rows = conn.execute(
            "SELECT * FROM map_node WHERE parent_path = ? ORDER BY node_kind DESC, name",
            (parent_path,),
        ).fetchall()
    return [dict(r) for r in rows]


def get_node(path: str) -> dict | None:
    with _conn() as conn:
        row = conn.execute("SELECT * FROM map_node WHERE path = ?", (path,)).fetchone()
    return dict(row) if row else None


def node_count() -> int:
    with _conn() as conn:
        return conn.execute("SELECT COUNT(*) FROM map_node").fetchone()[0]
