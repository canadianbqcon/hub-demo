"""Data layer for the vault structure map.

`map_node` is a CACHE of the filesystem: `refresh()` walks the tree, wipes the
table, and repopulates it in full (no SCD/history — the user chose
cache-overwrite semantics). The schema is owned by
db/migrations/vault_map/00*.sql; this module never CREATEs it.

The walker covers TWO real roots stitched under a synthetic super-root "@"
("second brain"): the Obsidian vault (path ".") and its sibling vault-code repo
(paths prefixed "vault-code/"). Everything is shown — no directory is skipped,
including .git internals and caches; tool-generated files are flagged
(`generated`) so the UI can recede them rather than hide them.

Every node is classified into the 10-bucket function model by INTRINSIC TELLS
(extension / frontmatter `type` / location-role / provenance), first-match-wins,
with NO silent default — an unplaceable authored file becomes a visible
`unclassified`. The model is specified in
docs/specs/2026-06-12-vault-map-production-design.md and was designed
live against the mockup at static/mockups/vault-map.html. Do NOT reintroduce a
folder-assignment classifier with an `ops` default — that junk drawer is the
thing this replaced.
"""

